def _h5_dir_equiv_for_window_cache(
    cached_dir: str, current_dir: str, allow_equivalent: bool
) -> bool:
    """
    判断缓存 attrs 里的 h5_dir 与当前配置是否视为同一数据源。

    allow_equivalent=False：仅当规范化后的绝对路径字符串完全一致。
    allow_equivalent=True：在 forecast 仍由调用方单独校验的前提下，
    允许 (1) realpath 相同，或 (2) 末级目录名相同（例如整库仅换挂载前缀）。

    注意：末级目录名相同不能保证数据一定相同；若需严格匹配可关闭 allow_equivalent
    或设置环境变量 WF_CACHE_H5_DIR_EQUIVALENT=0。
    """
    if cached_dir == current_dir:
        return True
    if not allow_equivalent:
        return False
    try:
        if os.path.realpath(cached_dir) == os.path.realpath(current_dir):
            return True
    except OSError:
        pass
    bn_c = os.path.basename(os.path.normpath(cached_dir))
    bn_u = os.path.basename(os.path.normpath(current_dir))
    return bool(bn_c) and bn_c == bn_u


def _date_int_to_burn_history_day_index(date_int: int) -> int:
    """将 yyyymmdd 转为相对 2000-01-01 的天数（0-based）。"""
    if date_int <= 0:
        return 0
    y = date_int // 10000
    m = (date_int % 10000) // 100
    d = date_int % 100
    from datetime import datetime
    try:
        dt = datetime(y, m, d)
        start = datetime(BURN_HISTORY_START_YEAR, 1, 1)
        return (dt - start).days
    except Exception:
        return 0


