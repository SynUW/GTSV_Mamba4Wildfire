def _read_patch_from_h5(f: h5py.File,
                        all_dataset_names: set,
                        center_row: int,
                        center_col: int,
                        patch_size: int) -> np.ndarray | None:
    """
    Read a (patch_size x patch_size) spatial patch centered at (center_row, center_col),
    returning an array of shape (C, H, W, T) where H=W=patch_size.

    Missing pixels are zero-filled.
    """
    r = patch_size // 2

    # Find one existing dataset to infer (C, T)
    base_arr = None
    for dr in range(-r, r + 1):
        for dc in range(-r, r + 1):
            name = f"{center_row + dr}_{center_col + dc}"
            if name in all_dataset_names:
                base_arr = f[name][:].astype(np.float32, copy=False)
                break
        if base_arr is not None:
            break
    if base_arr is None:
        return None

    C, T = int(base_arr.shape[0]), int(base_arr.shape[1])
    patch = np.zeros((C, patch_size, patch_size, T), dtype=np.float32)

    # Fill patch
    for i, dr in enumerate(range(-r, r + 1)):
        for j, dc in enumerate(range(-r, r + 1)):
            name = f"{center_row + dr}_{center_col + dc}"
            if name in all_dataset_names:
                try:
                    arr = f[name][:].astype(np.float32, copy=False)
                    if arr.shape == (C, T):
                        patch[:, i, j, :] = arr
                except Exception:
                    pass

    return patch  # (C, H, W, T)


def _process_pixel_year_batch_worker(args):
    """
    处理一批(像素,年份)组合的所有样本（模块级函数，支持多进程pickle）
    在独立进程中运行，直接读取窗口+进程内缓存
    🔥 优化组合：批量读取 + 向量化窗口构建 + 优化数据传输
    """
    pixel_year_batch, process_data_dict = args
    pixel_year_indices_map = process_data_dict['pixel_year_indices_map']
    sample_info_list = process_data_dict['sample_info_list']
    year_files = process_data_dict['year_files']
    C = process_data_dict['C']
    L = process_data_dict['L']
    lookback = process_data_dict['lookback']
    forecast = process_data_dict['forecast']
    patch_size = int(process_data_dict.get('patch_size', 1))
    
    # 重建sample_info_map（多进程需要）
    sample_info_map = {idx: info for idx, info in sample_info_list}
    
    # 🔥 方案3优化：返回紧凑的数据结构（减少序列化开销）
    batch_indices = []  # 样本索引列表
    batch_windows = []  # 窗口数据列表
    batch_meta = []  # 元数据列表
    batch_labels = []  # 标签列表
    
    try:
        # 🚀 优化：按像素-年份分组，每个进程批量处理多个组合
        # 缓存key: (year, center_row, center_col, patch_size) - 缓存整年patch数据，支持跨年
        # patch 会显著增大内存，默认缓存规模更小，可用环境变量覆盖
        default_patch_cache = '2000' if patch_size > 1 else '50000'
        max_cache_size = int(os.getenv('WF_PATCH_CACHE_SIZE' if patch_size > 1 else 'WF_PIXEL_CACHE_SIZE',
                                       default_patch_cache))
        pixel_cache = OrderedDict()  # LRU缓存：{(year, row, col, patch_size): full_year_patch_data}
        cache_hit_count = 0  # 统计缓存命中次数（像素级别）
        cache_miss_count = 0  # 统计缓存未命中次数
        
        # 🔥 优化：按年份分组处理，减少文件打开次数
        year_groups = {}
        for pixel_row, pixel_col, year in pixel_year_batch:
            if year not in year_groups:
                year_groups[year] = []
            year_groups[year].append((pixel_row, pixel_col))
        
        # 按年份顺序处理
        for year in sorted(year_groups.keys()):
            file_path = year_files.get(year)
            if not file_path or not os.path.exists(file_path):
                logger.warning(f"年份 {year} 的文件不存在，跳过该年份的所有组合")
                continue
            
            pixel_list = year_groups[year]
            
            # 打开文件句柄，在整个处理过程中保持打开（减少文件打开开销）
            with h5py.File(file_path, 'r', libver='latest') as f:
                all_dataset_names = set(f.keys())
                
                # 🔥 方案4：批量读取所有中心像素的整年patch数据
                pixel_data_dict = {}  # {(row,col): full_year_patch_data}
                for pixel_row, pixel_col in pixel_list:
                    cache_key = (year, int(pixel_row), int(pixel_col), int(patch_size))
                    if cache_key in pixel_cache:
                        pixel_data_dict[(pixel_row, pixel_col)] = pixel_cache[cache_key]
                        pixel_cache.move_to_end(cache_key)
                        cache_hit_count += 1
                        continue

                    # Read patch and cache
                    try:
                        patch_data = _read_patch_from_h5(f, all_dataset_names, int(pixel_row), int(pixel_col), patch_size)
                        pixel_data_dict[(pixel_row, pixel_col)] = patch_data
                        if patch_data is not None and len(pixel_cache) < max_cache_size:
                            pixel_cache[cache_key] = patch_data
                        cache_hit_count += 1 if patch_data is not None else 0
                        cache_miss_count += 1 if patch_data is None else 0
                    except Exception as e:
                        logger.debug(f"读取patch中心({pixel_row},{pixel_col}) 年份 {year} 失败: {e}")
                        pixel_data_dict[(pixel_row, pixel_col)] = None
                        cache_miss_count += 1
                
                # 🔥 方案2优化：按像素分组，向量化处理同一像素的所有样本
                for pixel_row, pixel_col in pixel_list:
                    current_year_data = pixel_data_dict.get((pixel_row, pixel_col))
                    
                    # 获取该像素-年份组合的所有样本索引
                    key = (pixel_row, pixel_col, year)
                    pixel_year_indices = pixel_year_indices_map.get(key, [])
                    
                    if not pixel_year_indices:
                        continue
                    
                    # 🔥 方案2：向量化处理 - 收集该像素的所有样本信息
                    pixel_samples = []
                    for idx in pixel_year_indices:
                        if idx not in sample_info_map:
                            continue
                        year_val, _, _, target_date, label = sample_info_map[idx]
                        pixel_samples.append((idx, target_date, label))
                    
                    if not pixel_samples:
                        continue
                    
                    # 🔥 方案2：批量计算所有样本的时间信息
                    target_dates = [s[1] for s in pixel_samples]
                    target_year_start = datetime(target_dates[0].year, 1, 1)
                    target_doys = np.array([(td - target_year_start).days for td in target_dates])
                    
                    # 检测跨年样本
                    history_starts = [td - dt.timedelta(days=lookback) for td in target_dates]
                    history_years = np.array([hs.year for hs in history_starts])
                    target_years = np.array([td.year for td in target_dates])
                    is_cross_year_mask = (history_years != target_years) | (target_doys < lookback)
                    
                    # 分别处理跨年和非跨年样本
                    cross_year_indices = [i for i, mask in enumerate(is_cross_year_mask) if mask]
                    normal_indices = [i for i, mask in enumerate(is_cross_year_mask) if not mask]
                    
                    # 🔥 方案2：非跨年样本的向量化处理
                    if normal_indices and current_year_data is not None:
                        normal_samples = [pixel_samples[i] for i in normal_indices]
                        normal_doys = target_doys[normal_indices]
                        
                        # 向量化构建窗口
                        num_normal = len(normal_samples)
                        normal_windows = np.zeros((num_normal, C, L), dtype=np.float32)
                        
                        # 批量计算past和future的索引范围
                        past_start_indices = np.maximum(0, normal_doys - lookback)
                        past_end_indices = normal_doys
                        future_start_indices = normal_doys
                        future_end_indices = np.minimum(current_year_data.shape[1], future_start_indices + forecast)
                        
                        # 向量化提取past部分
                        for i, (ps, pe) in enumerate(zip(past_start_indices, past_end_indices)):
                            past_len = pe - ps
                            if past_len > 0:
                                # 确保长度匹配
                                actual_past_len = min(past_len, lookback)
                                normal_windows[i, :, :actual_past_len] = current_year_data[:, ps:ps+actual_past_len]
                        
                        # 向量化提取future部分
                        for i, (fs, fe) in enumerate(zip(future_start_indices, future_end_indices)):
                            future_len = fe - fs
                            if future_len > 0:
                                actual_future_len = min(future_len, forecast)
                                normal_windows[i, :, lookback:lookback + actual_future_len] = current_year_data[:, fs:fs+actual_future_len]
                        
                        # 添加到结果
                        for i, sample_idx in enumerate(normal_indices):
                            idx, target_date, label = pixel_samples[sample_idx]
                            date_int = int(target_date.strftime('%Y%m%d'))
                            batch_indices.append(idx)
                            batch_windows.append(normal_windows[i])
                            batch_meta.append(np.array([date_int, int(pixel_row), int(pixel_col)], dtype=np.int64))
                            batch_labels.append(label)
                    
                    # 🔥 跨年样本逐个处理（因为需要读取前一年数据）
                    for i in cross_year_indices:
                        idx, target_date, label = pixel_samples[i]
                        
                        history_start = target_date - dt.timedelta(days=lookback)
                        future_end = target_date + dt.timedelta(days=forecast - 1)
                        target_year_start = datetime(target_date.year, 1, 1)
                        target_doy = (target_date - target_year_start).days
                        
                        history_year = history_start.year
                        prev_year = history_year
                        prev_year_file = year_files.get(prev_year)
                        
                        # 创建窗口
                        win = np.zeros((C, L), dtype=np.float32)
                        
                        # 读取前一年的数据（patch模式）
                        prev_year_data = None
                        if prev_year_file and os.path.exists(prev_year_file):
                            prev_cache_key = (prev_year, int(pixel_row), int(pixel_col), int(patch_size))
                            
                            if prev_cache_key in pixel_cache:
                                prev_year_data = pixel_cache[prev_cache_key]
                                pixel_cache.move_to_end(prev_cache_key)
                                cache_hit_count += 1
                            else:
                                cache_miss_count += 1
                                try:
                                    with h5py.File(prev_year_file, 'r') as prev_f:
                                        prev_names = set(prev_f.keys())
                                        prev_year_data = _read_patch_from_h5(prev_f, prev_names, int(pixel_row), int(pixel_col), patch_size)
                                        if prev_year_data is not None and len(pixel_cache) < max_cache_size:
                                            pixel_cache[prev_cache_key] = prev_year_data
                                except Exception as e:
                                    logger.debug(f"读取前一年 {prev_year} patch中心({pixel_row},{pixel_col})失败: {e}")
                                    prev_year_data = None
                        
                        # 填充窗口
                        past_filled = 0
                        
                        if prev_year_data is not None:
                            prev_year_start = datetime(prev_year, 1, 1)
                            prev_year_end = datetime(prev_year, 12, 31)
                            prev_year_data_start_idx = max(0, (history_start - prev_year_start).days)
                            prev_year_data_end_idx = (prev_year_end - prev_year_start).days + 1
                            prev_year_needed_days = prev_year_data_end_idx - prev_year_data_start_idx
                            
                            prev_data_len = min(prev_year_needed_days, lookback - past_filled)
                            if prev_data_len > 0:
                                win[:, past_filled:past_filled + prev_data_len] = prev_year_data[:, prev_year_data_start_idx:prev_year_data_start_idx + prev_data_len]
                                past_filled += prev_data_len
                        
                        if current_year_data is not None:
                            past_remaining = lookback - past_filled
                            if past_remaining > 0 and target_doy > 0:
                                past_end_idx = min(target_doy, past_remaining)
                                win[:, past_filled:past_filled + past_end_idx] = current_year_data[:, 0:past_end_idx]
                                past_filled += past_end_idx
                            
                            future_start_idx = target_doy
                            target_year_data_end_idx = (future_end - target_year_start).days + 1
                            future_end_idx = min(target_year_data_end_idx, future_start_idx + forecast)
                            future_len = future_end_idx - future_start_idx
                            if future_len > 0:
                                win[:, lookback:lookback + future_len] = current_year_data[:, future_start_idx:future_end_idx]
                        
                        date_int = int(target_date.strftime('%Y%m%d'))
                        batch_indices.append(idx)
                        batch_windows.append(win)
                        batch_meta.append(np.array([date_int, int(pixel_row), int(pixel_col)], dtype=np.int64))
                        batch_labels.append(label)
        
        # 🔥 方案3优化：返回紧凑的数据结构（numpy数组，减少序列化开销）
        if batch_indices:
            return {
                'indices': np.array(batch_indices, dtype=np.int64),
                'windows': np.stack(batch_windows, axis=0),  # (N, C, L)
                'meta': np.stack(batch_meta, axis=0),  # (N, 3)
                'labels': np.array(batch_labels, dtype=np.int8)  # (N,)
            }
        else:
            return {
                'indices': np.array([], dtype=np.int64),
                'windows': np.zeros((0, C, L), dtype=np.float32),
                'meta': np.zeros((0, 3), dtype=np.int64),
                'labels': np.array([], dtype=np.int8)
            }
        
    except Exception as e:
        logger.error(f"处理批次失败: {e}")
        import traceback
        logger.error(traceback.format_exc())
        # 返回零数据
        for pixel_row, pixel_col, year in pixel_year_batch:
            key = (pixel_row, pixel_col, year)
            pixel_year_indices = pixel_year_indices_map.get(key, [])
            for idx in pixel_year_indices:
                batch_indices.append(idx)
                batch_windows.append(np.zeros((C, L), dtype=np.float32))
                batch_meta.append(np.array([-1, -1, -1], dtype=np.int64))
                batch_labels.append(0)
        
        if batch_indices:
            return {
                'indices': np.array(batch_indices, dtype=np.int64),
                'windows': np.stack(batch_windows, axis=0),
                'meta': np.stack(batch_meta, axis=0),
                'labels': np.array(batch_labels, dtype=np.int8)
            }
        else:
            return {
                'indices': np.array([], dtype=np.int64),
                'windows': np.zeros((0, C, L), dtype=np.float32),
                'meta': np.zeros((0, 3), dtype=np.int64),
                'labels': np.array([], dtype=np.int8)
            }


