def _burn_history_unique_pixels_for_centers(patch_centers, patch_size):
    """给定 patch 中心列表与 patch_size，返回该批 patch 涉及的所有唯一 (row,col) 像素。"""
    half = patch_size // 2
    out = set()
    for r, c in patch_centers:
        for dr in range(-half, half + 1):
            for dc in range(-half, half + 1):
                out.add((int(r) + dr, int(c) + dc))
    return out


def _burn_history_read_year_chunk(args):
    """
    供多进程调用：按「文件键顺序」单遍扫描年度 H5（顺序 I/O），只读需要的像素，再在内存拼 patch。
    args: (year_file, patch_chunk, g0, patch_size, year)
    """
    if len(args) == 5:
        year_file, patch_chunk, g0, patch_size, year = args
    else:
        year_file, patch_chunk, g0, patch_size = args
        year = None
    if not patch_chunk:
        return []
    out = []
    try:
        unique = _burn_history_unique_pixels_for_centers(patch_chunk, patch_size)
        need_keys = {f"{r}_{c}" for (r, c) in unique}
        # 按 key 字典序单遍扫描，使同区域 key 连续，减少随机 I/O
        pixel_data = {}
        rdcc = 80 * 1024 * 1024  # 80MB 读缓存
        with h5py.File(year_file, "r", libver="latest", rdcc_nbytes=rdcc) as yf:
            for key in list(yf.keys()):
                if key not in need_keys:
                    continue
                try:
                    parts = key.split("_", 1)
                    r, c = int(parts[0]), int(parts[1])
                    arr = np.asarray(yf[key][0, :], dtype=np.float64)
                    arr = np.where((arr >= 0) & (arr <= 10), arr, 0.0)
                    pixel_data[(r, c)] = arr.astype(np.uint8)
                except (ValueError, IndexError, TypeError):
                    pass
        if pixel_data:
            ty = next(iter(pixel_data.values())).shape[0]
        else:
            ty = 366 if year and ((year % 4 == 0 and year % 100 != 0) or (year % 400 == 0)) else 365
        half = patch_size // 2
        for row, col in patch_chunk:
            row, col = int(row), int(col)
            patch = np.zeros((patch_size, patch_size, ty), dtype=np.uint8)
            for i, dr in enumerate(range(-half, half + 1)):
                for j, dc in enumerate(range(-half, half + 1)):
                    rr, cc = row + dr, col + dc
                    if (rr, cc) in pixel_data:
                        patch[i, j, :] = pixel_data[(rr, cc)]
            out.append((row, col, patch))
    except Exception:
        pass
    return out

