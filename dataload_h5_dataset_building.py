    def _find_strict_no_fire_pixels(self):
        """Find strict no-fire pixels (no fire in current day and ±5 days for each pixel)"""
        logger.info("Searching for strict no-fire pixels (no fire in current day and ±5 days for each pixel)...")
        
        # Always compute strict no-fire pixels from scratch (not cached to keep cache size manageable)
        logger.info("Computing strict no-fire pixels from scratch...")
        strict_no_fire_pixels = []
        
        # If tiff_dir is provided, use TIFF-based filtering
        if self.tiff_dir and os.path.exists(self.tiff_dir):
            logger.info(f"Using TIFF-based filtering from: {self.tiff_dir}")
            
            # 🚀 优化：使用流式处理避免内存溢出
            strict_no_fire_pixels = self._process_all_years_strict_no_fire_pixels_from_tiff_streaming()
        else:
            # Fallback to H5-based filtering
            logger.info("Using H5-based filtering (fallback)")
            
            # Use thread pool for parallel processing
            with ThreadPoolExecutor(max_workers=min(4, len(self.year_files))) as executor:
                futures = [
                    executor.submit(self._process_year_for_strict_no_fire_pixels, (year, file_path))
                    for year, file_path in self.year_files.items()
                ]
                
                for future in tqdm(as_completed(futures), total=len(futures), desc="Scanning years"):
                    try:
                        year_results = future.result()
                        strict_no_fire_pixels.extend(year_results)
                    except Exception as e:
                        logger.error(f"Error processing year: {e}")
        
        logger.info(f"Found {len(strict_no_fire_pixels)} strict no-fire pixel-day combinations")
        return strict_no_fire_pixels
    
    def _process_all_years_strict_no_fire_pixels_from_tiff_streaming(self):
        """
        流式处理版本：避免内存溢出
        分批处理年份，限制内存使用
        """
        logger.info("🚀 Processing all years with streaming approach (memory-optimized)...")
        all_strict_no_fire_pixels = []
        
        # 获取内存限制（MB）
        max_memory_mb = int(os.environ.get('WF_MAX_MEMORY_MB', '8192'))  # 默认8GB
        logger.info(f"📊 Memory limit: {max_memory_mb}MB")
        
        # 按年份分批处理
        years = sorted(self.year_files.keys())
        batch_size = max(1, len(years) // 4)  # 至少处理1年，最多4批
        
        for batch_start in range(0, len(years), batch_size):
            batch_years = years[batch_start:batch_start + batch_size]
            logger.info(f"🔄 Processing batch {batch_start//batch_size + 1}: years {batch_years}")
            
            # 处理当前批次的年份
            batch_pixels = self._process_years_batch_strict_no_fire_pixels(batch_years)
            all_strict_no_fire_pixels.extend(batch_pixels)
            
            # 检查内存使用
            memory_usage = psutil.Process().memory_info().rss / 1024 / 1024  # MB
            logger.info(f"📊 Current memory usage: {memory_usage:.1f}MB")
            
            if memory_usage > max_memory_mb * 0.8:  # 超过80%限制
                logger.warning(f"⚠️  Memory usage high ({memory_usage:.1f}MB), reducing batch size")
                batch_size = max(1, batch_size // 2)
            
            # 强制垃圾回收
            gc.collect()
        
        logger.info(f"✅ Streaming processing completed: {len(all_strict_no_fire_pixels)} pixels")
        return all_strict_no_fire_pixels
    
    def _process_years_batch_strict_no_fire_pixels(self, years):
        """处理一批年份的严格无火灾像素"""
        batch_pixels = []
        
        for year in years:
            logger.info(f"🔍 Processing year {year}...")
            year_pixels = self._process_single_year_strict_no_fire_pixels(year)
            batch_pixels.extend(year_pixels)
            logger.info(f"✅ Year {year}: {len(year_pixels)} pixels")
        
