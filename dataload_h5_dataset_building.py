    def _load_pixel_data_for_date_range(self, pixel_row, pixel_col, start_date, end_date):
        """Load data for specified pixel in specified date range - cross-file support"""
        # Group date ranges by year
        year_ranges = {}
        current_date = start_date
        
        while current_date <= end_date:
            year = current_date.year
            if year not in year_ranges:
                year_ranges[year] = []
            year_ranges[year].append(current_date)
            current_date += timedelta(days=1)
        
        data_segments = []
        num_channels_inferred = None
        
        # Batch load data by year
        for year in sorted(year_ranges.keys()):
            year_dates = year_ranges[year]
            
            if year not in self.year_files:
                # 🔥 关键修复：添加详细的年份文件缺失错误报告
                error_msg = f"❌ 年份文件缺失: {year}年H5文件不存在"
                error_msg += f" | 需要数据: {len(year_dates)}天 ({year_dates[0].strftime('%Y-%m-%d')} 到 {year_dates[-1].strftime('%Y-%m-%d')})"
                error_msg += f" | 可用年份: {sorted(self.year_files.keys())}"
                error_msg += f" | 像素位置: ({pixel_row}, {pixel_col})"
                
                logger.error(error_msg)
                continue
            
            try:
                file_path = self.year_files[year]
                f = self._get_file_handle(file_path)
                if f is None:
                    # 🔥 关键修复：添加文件打开失败的详细错误报告
                    error_msg = f"❌ 文件打开失败: 无法打开H5文件 {file_path}"
                    error_msg += f" | 年份: {year} | 需要数据: {len(year_dates)}天"
                    error_msg += f" | 像素位置: ({pixel_row}, {pixel_col})"
                    error_msg += f" | 可能原因: 文件损坏、权限不足、磁盘空间不足"
                    
                    logger.error(error_msg)
                    continue
                
                pixel_name = f"{pixel_row}_{pixel_col}"
                
                if pixel_name not in f:
                    # 🔥 关键修复：添加像素不存在的详细错误报告
                    error_msg = f"❌ 像素不存在: 像素 {pixel_name} 在{year}年H5文件中不存在"
                    error_msg += f" | 文件路径: {file_path}"
                    error_msg += f" | 需要数据: {len(year_dates)}天 ({year_dates[0].strftime('%Y-%m-%d')} 到 {year_dates[-1].strftime('%Y-%m-%d')})"
                    error_msg += f" | 可能原因: 像素超出范围、数据未生成、坐标错误"
                    
                    logger.error(error_msg)
                    continue
                
                # 优化：只加载需要的时间段，而不是整个年度数据
                # 计算需要加载的时间范围
                year_start_date = datetime(year, 1, 1)
                year_end_date = datetime(year, 12, 31)
                
                # 确定实际需要的时间范围
                actual_start = max(start_date, year_start_date)
                actual_end = min(end_date, year_end_date)
                
                # 计算需要加载的天数
                start_doy = (actual_start - year_start_date).days
                end_doy = (actual_end - year_start_date).days
                required_days = end_doy - start_doy + 1
                
                # 只加载需要的时间段数据
                if required_days <= 0:
                    continue
                
                # 确保索引不超出范围
                max_days = f[pixel_name].shape[1]
                if end_doy >= max_days:
                    end_doy = max_days - 1
                    required_days = end_doy - start_doy + 1
                
                pixel_data = f[pixel_name][:, start_doy:end_doy+1]  # 只加载需要的时间段
                if pixel_data.ndim != 2:
                    continue
                
                if num_channels_inferred is None:
                    num_channels_inferred = int(pixel_data.shape[0])
                
                # Calculate day indices with leap year handling
                year_start = datetime(year, 1, 1)
                
                year_data_list = []
                for date in year_dates:
                    doy = (date - year_start).days  # Day of year (0-based)
                    
                    # 计算在加载的数据段中的相对索引
                    relative_doy = doy - start_doy
                    
                    # 检查相对索引是否在加载的数据范围内
                    if relative_doy < 0 or relative_doy >= pixel_data.shape[1]:
                        continue
            
                    # 使用相对索引，因为我们已经只加载了需要的数据
                    day_idx = relative_doy
                    
                    # 最终边界检查
                    if day_idx >= pixel_data.shape[1] or day_idx < 0:
                        continue
                    
                    year_data_list.append(pixel_data[:, day_idx:day_idx+1])
                
                # Merge annual data
                if year_data_list:
                    year_data = np.concatenate(year_data_list, axis=1)
                    data_segments.append(year_data)
                else:
                    continue
                    
            except Exception as e:
                logger.warning(f"Error loading data for year {year}: {e}, skipping {len(year_dates)} days")
                continue
        
        # Concatenate all year data
        if data_segments:
            full_data = np.concatenate(data_segments, axis=1)
            # Check if we have the expected length
            expected_length = (end_date - start_date).days + 1
            if full_data.shape[1] != expected_length:
                logger.warning(f"Data length mismatch: expected {expected_length}, got {full_data.shape[1]} for range {start_date} to {end_date}")
                return None
            return full_data
        else:
            # No data segments - return None silently
            return None
    
