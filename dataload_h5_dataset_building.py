    def _has_invalid_data(self, past_data, future_data):
        """
        检查数据是否包含无效值
        
        Args:
            past_data: 历史数据 (channels, time_steps)
            future_data: 未来数据 (channels, time_steps)
            
        Returns:
            bool: True表示数据无效，False表示数据有效
        """
        # 合并past和future数据进行统一检查
        combined_data = torch.cat([past_data, future_data], dim=1)  # (channels, total_time)
        
        # 1. 检查FIRMS通道（通道0）是否包含255（NoData）
        firms_channel = combined_data[0, :]  # FIRMS通道
        if torch.any(firms_channel == 255):
            return True
        
        # 2. 检查任意通道是否包含-32768（NoData）
        if torch.any(combined_data < 0):
            return True
        
        # 3. 检查任意通道是否包含小于0的值（无效值，除了已经检查的-32768）
        if torch.any(combined_data < 0):
            return True
        
        # 数据有效
        return False
    
