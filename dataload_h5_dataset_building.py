    def _process_single_year_strict_no_fire_pixels(self, year):
        """处理单个年份的严格无火灾像素（内存优化版本）"""
        year_pixels = []
        
        try:
            # 获取该年份的TIFF文件
            tiff_pattern = os.path.join(self.tiff_dir, f"{year}_*.tif")
            tiff_files = glob.glob(tiff_pattern)
            
            if not tiff_files:
                logger.warning(f"No TIFF files found for year {year}")
                return year_pixels
            
            # 按日期排序
            tiff_files.sort()
            
            # 获取图像尺寸
            ds_first = gdal.Open(tiff_files[0], gdal.GA_ReadOnly)
            height, width = ds_first.RasterYSize, ds_first.RasterXSize
            
            logger.info(f"📐 Year {year}: {len(tiff_files)} files, {height}x{width} pixels")
            
            # 分批加载TIFF文件（避免一次性加载所有文件）
            batch_size = min(30, len(tiff_files))  # 每次最多加载30个文件
            
            for batch_start in range(0, len(tiff_files), batch_size):
                batch_files = tiff_files[batch_start:batch_start + batch_size]
                logger.info(f"📁 Loading batch {batch_start//batch_size + 1}: {len(batch_files)} files")
                
                # 加载当前批次的TIFF数据
                batch_data = {}
                for tiff_file in batch_files:
                    try:
                        ds = gdal.Open(tiff_file, gdal.GA_ReadOnly)
                        band = ds.GetRasterBand(1)
                        data = band.ReadAsArray()
                        data = np.where(data == 255, np.nan, data)
                        data = np.nan_to_num(data, nan=0.0)
                        batch_data[tiff_file] = data
                    except Exception as e:
                        logger.warning(f"Failed to read {tiff_file}: {e}")
                        continue
                
                # 处理当前批次的像素
                batch_pixels = self._find_strict_no_fire_pixels_in_batch(batch_data, year)
                year_pixels.extend(batch_pixels)
                
                # 清理内存
                del batch_data
                gc.collect()
            
            logger.info(f"✅ Year {year} completed: {len(year_pixels)} pixels")
            
        except Exception as e:
            logger.error(f"Error processing year {year}: {e}")
        
        return year_pixels
    
