    def _sample_from_pools(self, positive_samples, negative_pool):
        """Sample from pools based on ratios, per (year, LULC) combination"""
        logger.info("🎯 Stage 2: Sampling from pools based on ratios (per year×LULC)...")
        logger.info(f"🔍 Applying sampling ratios : positive_ratio={self.positive_ratio}, pos_neg_ratio={self.pos_neg_ratio}")
        
        # 验证负样本池是否有效
        if len(negative_pool) == 0:
            logger.error("❌ Negative pool is empty! Cannot proceed with sampling.")
            logger.error("🔍 This usually means:")
            logger.error("   1. LULC data is missing or corrupted")
            logger.error("   2. No no-fire days found for any LULC type")
            logger.error("   3. All negative candidates failed validation")
            logger.error("   4. LULC data directory is not set correctly")
            raise ValueError("Negative pool is empty - cannot proceed with sampling")
        
        rng = random.Random(getattr(self, 'random_seed', 42))
        
        # 按 (year, LULC) 组合分组
        buckets_pos = defaultdict(list)
        buckets_neg = defaultdict(list)
        for s in positive_samples:
            key = (int(s['year']), int(s.get('lulc_type', -1)))
            buckets_pos[key].append(s)
        for s in negative_pool:
            key = (int(s['year']), int(s.get('lulc_type', -1)))
            buckets_neg[key].append(s)
        
        selected_pos = []
        selected_neg = []
        
        # 对每个 (year, LULC) 组合分别应用采样比例
        for key in sorted(set(list(buckets_pos.keys()) + list(buckets_neg.keys()))):
            pos_list = buckets_pos.get(key, [])
            neg_list = buckets_neg.get(key, [])
            if not pos_list:
                continue
            
            # Apply positive ratio
            if self.positive_ratio < 1.0:
                keep = max(1, int(math.ceil(len(pos_list) * self.positive_ratio)))
                pos_sel = rng.sample(pos_list, keep) if keep < len(pos_list) else pos_list
            else:
                pos_sel = pos_list
            
            # Apply pos-neg ratio
            if math.isfinite(self.pos_neg_ratio) and pos_sel:
                target_neg = int(len(pos_sel) * self.pos_neg_ratio)
                if target_neg <= 0:
                    neg_sel = []
                elif len(neg_list) > target_neg:
                    neg_sel = rng.sample(neg_list, target_neg)
                else:
                    neg_sel = neg_list
            else:
                neg_sel = neg_list
            
            selected_pos.extend(pos_sel)
            selected_neg.extend(neg_sel)
        
        if self.verbose_sampling:
            tp, tn = len(selected_pos), len(selected_neg)
            ratio = (tn / tp) if tp > 0 else float('inf')
            logger.info(f"✅ Final sampling: {tp} positive, {tn} negative, ratio 1:{ratio:.2f}")
        
        return selected_pos, selected_neg
    
