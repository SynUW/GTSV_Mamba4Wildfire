    def _sample_lulc_pixels_vectorized(self, lulc_pixels, year_time_indices, spatiotemporal_mask):
        """向量化的LULC像素抽样方法（高度优化版）- 返回numpy数组"""
        if len(lulc_pixels[0]) == 0:
            return (np.array([], dtype=np.int32), np.array([], dtype=np.int32), np.array([], dtype=np.int32))
        
        # 确保year_time_indices是numpy数组
        year_time_indices = np.asarray(year_time_indices, dtype=np.int32)
        
        # 批量处理像素
        rows, cols = lulc_pixels[0], lulc_pixels[1]
        
        # 向量化检查所有像素在有效时间范围内的所有时间
        # 使用高级索引一次性获取所有像素的时间数据
        pixel_time_mask = spatiotemporal_mask[rows, cols, :][:, year_time_indices]
        
        # 找到有效的时间组合（使用NumPy的nonzero操作）
        valid_pixel_indices, valid_time_indices = np.nonzero(~pixel_time_mask)
        
        if len(valid_pixel_indices) > 0:
            # 直接返回numpy数组，避免Python列表构建
            return (rows[valid_pixel_indices], cols[valid_pixel_indices], year_time_indices[valid_time_indices])
        
        return (np.array([], dtype=np.int32), np.array([], dtype=np.int32), np.array([], dtype=np.int32))
    

