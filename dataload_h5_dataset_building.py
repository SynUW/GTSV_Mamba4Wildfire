    def _find_year_files(self):
        """Find all year dataset files"""
        year_files = {}
        pattern = os.path.join(self.h5_dir, "*_year_dataset.h5")
        
        for file_path in glob.glob(pattern):
            try:
                # Extract year from filename
                filename = os.path.basename(file_path)
                year_str = filename.split('_')[0]
                year = int(year_str)
                
                # Apply year filter if specified
                if self.years is not None and year not in self.years:
                    continue
                
                year_files[year] = file_path
                
            except (ValueError, IndexError) as e:
                logger.warning(f"Could not parse year from filename {filename}: {e}")
                continue
        
        return year_files
    
    def _clean_old_cache_files(self):
        """Clean old cache files to save disk space"""
        try:
            cache_files = glob.glob(os.path.join(self.cache_dir, "tiff_samples_*.h5"))
            if len(cache_files) > 5:  # Keep only the 5 most recent cache files
                # Sort by modification time
                cache_files.sort(key=os.path.getmtime, reverse=True)
                
                # Remove old cache files
                for old_cache in cache_files[5:]:
                    try:
                        os.remove(old_cache)
                        logger.info(f"🗑️ Removed old cache file: {os.path.basename(old_cache)}")
                    except Exception as e:
                        logger.warning(f"Failed to remove old cache file {old_cache}: {e}")
                        
        except Exception as e:
            logger.warning(f"Failed to clean old cache files: {e}")
    
    def _get_cache_file_path(self):
        """Get cache file path based on parameters"""
        # Create a hash of all parameters that affect the dataset
        params = {
            'h5_dir': self.h5_dir,
            'years': self.years,
            'lookback_seq': self.lookback_seq,
            'forecast_hor': self.forecast_hor,
            'min_fire_threshold': self.min_fire_threshold,
            'pos_neg_ratio': self.pos_neg_ratio,
            'positive_ratio': self.positive_ratio,
            'random_seed': self.random_seed,
            'strict_negative': True,  # Mark this as strict negative version
            'tiff_based': True,  # Mark this as TIFF-based version
            'version': '5.0',  # New version with seq_len/pred_len optimization
            'seq_len': self.lookback_seq,  # 🔥 关键：包含序列长度参数
            'pred_len': self.forecast_hor   # 🔥 关键：包含预测长度参数
        }
        
        params_str = json.dumps(params, sort_keys=True)
        params_hash = hashlib.md5(params_str.encode()).hexdigest()
        
        return os.path.join(self.cache_dir, f'tiff_samples_{params_hash}.h5')
    
