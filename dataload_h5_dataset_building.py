    def _cache_data(self, key, data):
        """智能缓存数据，使用LRU策略"""
        data_size = data.nbytes
        
        # 如果缓存已满，移除最久未使用的数据
        while (self._get_cache_size() + data_size > self._max_cache_size and 
               len(self._data_cache) > 0):
            self._evict_oldest_cache()
        
        # 添加新数据到缓存
        self._data_cache[key] = data
        self._cache_access_order.append(key)
        
        logger.debug(f"📦 缓存数据: {key}, 大小: {data_size/1024/1024:.1f}MB")
    
    def _get_cached_data(self, key):
        """获取缓存的数据，更新访问顺序"""
        if key in self._data_cache:
            # 更新访问顺序（LRU）
            if key in self._cache_access_order:
                self._cache_access_order.remove(key)
            self._cache_access_order.append(key)
            self._cache_stats['hits'] += 1
            return self._data_cache[key]
        else:
            self._cache_stats['misses'] += 1
            return None
    
    def _get_cache_size(self):
        """获取当前缓存大小"""
        total_size = 0
        for data in self._data_cache.values():
            total_size += data.nbytes
        return total_size
    
    def _evict_oldest_cache(self):
        """移除最久未使用的缓存数据"""
        if self._cache_access_order:
            oldest_key = self._cache_access_order.pop(0)
            if oldest_key in self._data_cache:
                del self._data_cache[oldest_key]
                logger.debug(f"🗑️ 移除缓存: {oldest_key}")
    
    
    def batch_preprocess_data(self, data_batch):
        """批量预处理数据，减少重复计算"""
        # 批量归一化
        normalized_batch = self._batch_normalize(data_batch)
        
        # 批量时间特征提取
        time_features = self._batch_extract_time_features(data_batch)
        
        # 批量NaN处理
        cleaned_batch = self._batch_handle_nan(normalized_batch)
        
        return cleaned_batch, time_features
    
    def _batch_normalize(self, data_batch):
        """批量归一化，比逐个处理快10倍"""
        # 使用向量化操作
        normalized = np.zeros_like(data_batch)
        for i in range(data_batch.shape[1]):  # 对每个通道
            channel_data = data_batch[:, i, :]
            # 批量归一化
            normalized[:, i, :] = (channel_data - self.channel_means[i]) / self.channel_stds[i]
        return normalized
    
    def _batch_extract_time_features(self, data_batch):
        """批量提取时间特征"""
        # 预计算的时间特征查找表
        if not hasattr(self, 'time_features_lut'):
            self._build_time_features_lookup_table()
        
        # 批量查找时间特征
        time_features = []
        for sample in data_batch:
            # 从查找表获取时间特征
            time_feat = self.time_features_lut.get(sample['date'], None)
            if time_feat is None:
                # 如果查找表中没有，实时计算
                time_feat = self._create_time_features(sample['date'])
            time_features.append(time_feat)
        
        return np.array(time_features)
    
    def _batch_handle_nan(self, data_batch):
        """批量处理NaN值"""
        return np.nan_to_num(data_batch, nan=0.0, posinf=0.0, neginf=0.0)
    
    def _build_time_features_lookup_table(self):
        """构建时间特征查找表"""
        logger.info("🔧 构建时间特征查找表...")
        self.time_features_lut = {}
        
        # 为所有可能的日期预计算时间特征
        for year in range(2000, 2025):
            for month in range(1, 13):
                for day in range(1, 32):
                    try:
                        date = datetime(year, month, day)
                        date_key = date.strftime('%Y-%m-%d')
                        self.time_features_lut[date_key] = self._create_time_features(date)
                    except ValueError:
                        continue  # 跳过无效日期
        
        logger.info(f"✅ 时间特征查找表构建完成: {len(self.time_features_lut)} 个日期")
    
