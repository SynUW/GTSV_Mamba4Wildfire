    def _calculate_spatial_distance_to_positive_samples(self, candidate_pixel, positive_samples):
        """计算候选像素到最近正样本的欧几里得距离"""
        candidate_row, candidate_col = candidate_pixel
        
        min_distance = float('inf')
        for pos_sample in positive_samples:
            pos_row, pos_col = pos_sample['pixel_row'], pos_sample['pixel_col']
            distance = np.sqrt((candidate_row - pos_row)**2 + (candidate_col - pos_col)**2)
            min_distance = min(min_distance, distance)
        
        return min_distance
    
