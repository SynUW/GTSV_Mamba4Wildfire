    def _get_all_valid_pixels(self):
        """
        获取所有有效像素位置（从H5文件中扫描）
        由于所有年份的H5文件都来自同一空间区域，只需扫描一年即可
        """
        logger.info("📍 Scanning H5 files to get all valid pixel locations...")
        valid_pixels = set()
        
        # 只扫描一年的H5文件即可，因为所有年份的像素位置都是一致的
        sample_year = 2020  # 选择一个中间年份作为样本
        h5_file_path = self._get_h5_file_path(sample_year)
        
        if not os.path.exists(h5_file_path):
            # 如果2020年不存在，尝试其他年份
            for year in range(2000, 2025):
                h5_file_path = self._get_h5_file_path(year)
                if os.path.exists(h5_file_path):
                    sample_year = year
                    break
            else:
                logger.error("No H5 files found!")
                return []
        
        logger.info(f"📍 Using year {sample_year} as sample for valid pixel detection")
        
        try:
            with h5py.File(h5_file_path, 'r') as f:
                # 获取所有像素名称
                pixel_names = list(f.keys())
                for pixel_name in pixel_names:
                    if '_' in pixel_name:
                        try:
                            row, col = map(int, pixel_name.split('_'))
                            valid_pixels.add((row, col))
                        except ValueError:
                            continue
        except Exception as e:
            logger.error(f"Error scanning H5 file {sample_year}: {e}")
            return []
        
        valid_pixels_list = list(valid_pixels)
        logger.info(f"📊 Found {len(valid_pixels_list)} valid pixel locations from year {sample_year}")
        return valid_pixels_list
    
    def _scan_all_tiff_files_for_positive_samples(self, valid_pixels):
        """
        扫描所有TIFF文件，提取正样本（不分年份）
        """
        logger.info("🔥 Scanning all TIFF files for positive samples...")
        positive_samples = []
        
        # 创建有效像素的集合用于快速查找
        valid_pixels_set = set(valid_pixels)
        
        # 获取所有TIFF文件
        all_tiff_files = []
        for year in range(2000, 2025):
            tiff_pattern = os.path.join(self.tiff_dir, f"{year}_*.tif")
            year_tiff_files = glob.glob(tiff_pattern)
            all_tiff_files.extend(year_tiff_files)
        
        logger.info(f"📁 Found {len(all_tiff_files)} TIFF files to process")
        
        # 处理所有TIFF文件
        for tiff_file in tqdm(all_tiff_files, desc="Processing TIFF files"):
            try:
                # 从文件名提取日期
                filename = os.path.basename(tiff_file)
                date_match = re.search(r'(\d{4})_(\d{2})_(\d{2})', filename)
                if not date_match:
                    continue
                
                year_str, month_str, day_str = date_match.groups()
                date = datetime(int(year_str), int(month_str), int(day_str))
                year = int(year_str)
                
                # 读取TIFF文件
                from osgeo import gdal
                ds = gdal.Open(tiff_file, gdal.GA_ReadOnly)
                if ds is None:
                    continue
                
                band = ds.GetRasterBand(1)
                data = band.ReadAsArray()
                ds = None
                
                if data is None:
                    continue
                
                # 查找火灾像素
                fire_rows, fire_cols = np.where(data >= self.min_fire_threshold)
                
                # 处理每个火灾像素
                for r, c in zip(fire_rows, fire_cols):
                    # 检查是否为有效像素
                    if (r, c) not in valid_pixels_set:
                        continue
                    
                    # 获取FIRMS值
                    firms_value = data[r, c]
                    
                    # 计算day_of_year
                    start_date = datetime(year, 1, 1)
                    day_of_year = (date - start_date).days
                    
                    sample = {
                        'year': year,
                        'day_of_year': day_of_year,
                        'date': date,
                        'pixel_row': int(r),
                        'pixel_col': int(c),
                        'firms_value': float(firms_value),
                        'lulc_type': None,  # 稍后添加LULC信息
                        'file_path': self.year_files.get(year, '')
                    }
                    
                    # 验证样本有效性
                    if self._is_sample_valid(sample):
                        positive_samples.append(sample)
            
            except Exception as e:
                logger.warning(f"Error processing TIFF file {tiff_file}: {e}")
                continue
        
        logger.info(f"📊 Found {len(positive_samples)} valid positive samples from TIFF scanning")
        return positive_samples
    
    def _associate_lulc_with_positive_samples(self, positive_samples):
        """
        为正样本建立LULC联系
        """
        logger.info("🌍 Building LULC associations for positive samples...")
        
        # 按年份分组处理LULC数据
        year_groups = {}
        for sample in positive_samples:
            year = sample['year']
            if year not in year_groups:
                year_groups[year] = []
            year_groups[year].append(sample)
        
        # 为每个年份的样本添加LULC信息
        for year, samples in year_groups.items():
            logger.info(f"🌍 Processing LULC for year {year} ({len(samples)} samples)")
            
            # 加载该年份的LULC数据
            lulc_data_dict = self._load_lulc_data_for_year(year)
            if lulc_data_dict is None:
                logger.warning(f"Could not load LULC data for year {year}, skipping...")
                continue
            
            # 提取LULC数据数组
            lulc_data = lulc_data_dict['data']
            
            # 为每个样本添加LULC类型
            for sample in samples:
                pixel_row = sample['pixel_row']
                pixel_col = sample['pixel_col']
                
                if 0 <= pixel_row < lulc_data.shape[0] and 0 <= pixel_col < lulc_data.shape[1]:
                    sample['lulc_type'] = int(lulc_data[pixel_row, pixel_col])
                else:
                    sample['lulc_type'] = None
        
        logger.info(f"📊 LULC association completed for {len(positive_samples)} samples")
        return positive_samples
    
    
    def _find_positive_samples(self):
        """Find positive samples using vectorized TIFF datacube scanning."""
        logger.info("🔥 Finding positive samples using multi-process parallel loading...")

        try:
            tiff_files = glob.glob(os.path.join(self.tiff_dir, "*.tif"))
            if not tiff_files:
                logger.warning(f"No TIFF files found in {self.tiff_dir}")
                return []
        
            logger.info(f"Found {len(tiff_files)} TIFF files to process")

            tiff_files_with_dates = []
            for tiff_file in tiff_files:
                filename = os.path.basename(tiff_file)
                m = re.search(r'(\d{4})_(\d{2})_(\d{2})', filename)
                if m:
                    y, mo, d = map(int, m.groups())
                    tiff_files_with_dates.append((datetime(y, mo, d), tiff_file))
            tiff_files_with_dates.sort(key=lambda x: x[0])
            sorted_files = [p[1] for p in tiff_files_with_dates]
            sorted_dates = [p[0] for p in tiff_files_with_dates]

            logger.info(f"Processing {len(sorted_files)} sorted TIFF files...")

            ds0 = gdal.Open(sorted_files[0], gdal.GA_ReadOnly)
            height, width = ds0.RasterYSize, ds0.RasterXSize
            ds0 = None

            def read_single_tiff(args):
                i, tiff_file = args
                try:
                    ds = gdal.Open(tiff_file, gdal.GA_ReadOnly)
                    if ds is None:
                        return i, np.zeros((height, width), dtype=np.uint8)
                    arr = ds.GetRasterBand(1).ReadAsArray()
                    return i, arr
                except Exception:
                    return i, np.zeros((height, width), dtype=np.uint8)

            data_3d = np.empty((len(sorted_files), height, width), dtype=np.uint8)
            max_workers = min(16, os.cpu_count() or 1)
            with ThreadPoolExecutor(max_workers=max_workers) as executor:
                for i, arr in tqdm(executor.map(read_single_tiff, [(i, f) for i, f in enumerate(sorted_files)]), total=len(sorted_files), desc="Reading TIFF files in parallel"):
                    data_3d[i] = arr

            global_mask_arr = None
            try:
                if getattr(self, 'global_avlid', None) and os.path.isfile(self.global_avlid):
                    ds_mask = gdal.Open(self.global_avlid, gdal.GA_ReadOnly)
                    if ds_mask is not None:
                        global_mask_arr = ds_mask.GetRasterBand(1).ReadAsArray()
            except Exception:
                pass

            # 缓存 datacube 与日期，供后续负样本/缓存步骤使用
            try:
                self.data_3d = data_3d
                self.dates = sorted_dates
                self.global_mask_arr = global_mask_arr
                if hasattr(self, '_save_datacube_cache'):
                    self._save_datacube_cache(data_3d, sorted_dates, global_mask_arr)
            except Exception:
                pass

            valid_mask = data_3d != 255
            fire_mask = (data_3d >= self.min_fire_threshold) & valid_mask
            if isinstance(global_mask_arr, np.ndarray):
                spatial_valid = (global_mask_arr == 1)
                fire_mask &= spatial_valid[np.newaxis, :, :]

            if not np.any(fire_mask):
                logger.warning("No positive samples found")
                return []

            num_days = data_3d.shape[0]
            eff_bottom = max(int(365), int(self.lookback_seq))
            eff_top = min(int(num_days - 7), int(num_days - self.forecast_hor))
            ti, rr, cc = np.where(fire_mask)
            valid_time_mask = (ti >= eff_bottom) & (ti < eff_top)
            if not np.any(valid_time_mask):
                logger.warning("All positives fall into excluded head/tail windows; returning empty list")
                return []
            ti = ti[valid_time_mask]
            rr = rr[valid_time_mask]
            cc = cc[valid_time_mask]
            fire_values = data_3d[ti, rr, cc]

            lulc_cache = {}
            def get_lulc_for_year(year: int):
                if year in lulc_cache:
                    return lulc_cache[year]
                try:
                    pattern = os.path.join(self.lulc_dir, f"{year}_*.tif")
                    matches = glob.glob(pattern)
                    if not matches:
                        lulc_cache[year] = None
                        return None
                    ds_lulc = gdal.Open(matches[0], gdal.GA_ReadOnly)
                    if ds_lulc is None:
                        lulc_cache[year] = None
                        return None
                    arr = ds_lulc.GetRasterBand(1).ReadAsArray()
                    lulc_cache[year] = arr
                    return arr
                except Exception:
                    lulc_cache[year] = None
                    return None

            positive_samples = []
            for i in range(len(ti)):
                t_idx = int(ti[i])
                date = sorted_dates[t_idx]
                r = int(rr[i]); c = int(cc[i])
                lulc_arr = get_lulc_for_year(date.year)
                lulc_val = int(lulc_arr[r, c]) if isinstance(lulc_arr, np.ndarray) else -1
                positive_samples.append({
                    'year': date.year,
                    'day_of_year': date.timetuple().tm_yday,
                    'date': date,
                    'pixel_row': r,
                    'pixel_col': c,
                    'firms_value': float(fire_values[i]),
                    'time_index': t_idx,
                    'lulc_type': lulc_val,
                })

            # 已在上方提前缓存 datacube

        except Exception as e:
            logger.error(f"Error scanning TIFF files: {e}")
            return []

        logger.info(f"Found {len(positive_samples)} positive samples from TIFF files")
        return positive_samples

